import 'package:supabase_flutter/supabase_flutter.dart';

import '../../domain/entities/account.dart';
import '../../domain/repositories/account_repository.dart';
import '../models/account_model.dart';

class AccountRepositoryImpl implements AccountRepository {
  final SupabaseClient supabase;

  AccountRepositoryImpl({required this.supabase});

  @override
  Future<List<Account>> getAllAccounts() async {
    try {
      final response = await supabase
          .from('accounts')
          .select()
          .order('created_at', ascending: false);

      return (response as List)
          .map((json) => AccountModel.fromJson(json))
          .toList();
    } catch (e) {
      throw Exception('Failed to load accounts: $e');
    }
  }

  @override
  Future<Account> getAccountById(int id) async {
    try {
      final response =
          await supabase.from('accounts').select().eq('id', id).single();

      return AccountModel.fromJson(response);
    } catch (e) {
      throw Exception('Failed to load account: $e');
    }
  }

  @override
  Future<Account> createAccount(Account account) async {
    try {
      final model = AccountModel(
        id: 0, // Will be generated by Supabase
        userId: account.userId,
        name: account.name,
        accountType: account.accountType,
        lastFour: account.lastFour,
        balance: account.balance,
        iconKey: account.iconKey,
        color: account.color,
        isLinked: account.isLinked,
        createdAt: DateTime.now(),
        updatedAt: DateTime.now(),
      );

      final response = await supabase
          .from('accounts')
          .insert(model.toJson())
          .select()
          .single();

      return AccountModel.fromJson(response);
    } catch (e) {
      throw Exception('Failed to create account: $e');
    }
  }

  @override
  Future<Account> updateAccount(Account account) async {
    try {
      final model = AccountModel(
        id: account.id,
        userId: account.userId,
        name: account.name,
        accountType: account.accountType,
        lastFour: account.lastFour,
        balance: account.balance,
        iconKey: account.iconKey,
        color: account.color,
        isLinked: account.isLinked,
        createdAt: account.createdAt,
        updatedAt: DateTime.now(),
      );

      final response = await supabase
          .from('accounts')
          .update(model.toJson())
          .eq('id', account.id)
          .select()
          .single();

      return AccountModel.fromJson(response);
    } catch (e) {
      throw Exception('Failed to update account: $e');
    }
  }

  @override
  Future<void> deleteAccount(int id) async {
    try {
      await supabase.from('accounts').delete().eq('id', id);
    } catch (e) {
      throw Exception('Failed to delete account: $e');
    }
  }
}
