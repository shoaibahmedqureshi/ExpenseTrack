-- Growth Tasks Table for KAN-19 Marketing Execution

CREATE TABLE IF NOT EXISTS growth_tasks (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  task_key text NOT NULL UNIQUE,
  platform text NOT NULL, -- reddit, product_hunt, hacker_news, pinterest, aso, reviews
  title text NOT NULL,
  description text NOT NULL,
  target_audience text,
  estimated_impact text, -- high, medium, low
  execution_plan text, -- Generated by growth_agent
  status text DEFAULT 'ready_for_execution', -- ready_for_execution, in_progress, completed, blocked
  assigned_to text, -- Team member email
  start_date timestamp,
  completed_date timestamp,
  notes text,
  created_at timestamp DEFAULT now(),
  updated_at timestamp DEFAULT now(),
  UNIQUE(task_key)
);

-- Index for quick filtering by platform and status
CREATE INDEX idx_growth_tasks_platform ON growth_tasks(platform);
CREATE INDEX idx_growth_tasks_status ON growth_tasks(status);
CREATE INDEX idx_growth_tasks_impact ON growth_tasks(estimated_impact);

-- Enable RLS
ALTER TABLE growth_tasks ENABLE ROW LEVEL SECURITY;

-- Service role can do everything (for agent)
CREATE POLICY "service_role_all" ON growth_tasks
  FOR ALL
  USING (auth.role() = 'service_role')
  WITH CHECK (auth.role() = 'service_role');

-- Public read-only access for tracking dashboard
CREATE POLICY "public_read" ON growth_tasks
  FOR SELECT
  USING (true);

-- Growth Task Execution Log
CREATE TABLE IF NOT EXISTS growth_executions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  task_key text NOT NULL,
  execution_type text, -- post, comment, engagement, content_created, submitted
  platform_url text,
  status text, -- draft, posted, scheduled, failed
  engagement_metrics jsonb, -- {views, likes, comments, shares, clicks}
  notes text,
  executed_by text,
  executed_at timestamp DEFAULT now(),
  FOREIGN KEY (task_key) REFERENCES growth_tasks(task_key) ON DELETE CASCADE
);

CREATE INDEX idx_growth_executions_task_key ON growth_executions(task_key);
CREATE INDEX idx_growth_executions_status ON growth_executions(status);

-- Enable RLS on executions log
ALTER TABLE growth_executions ENABLE ROW LEVEL SECURITY;

CREATE POLICY "service_role_all_executions" ON growth_executions
  FOR ALL
  USING (auth.role() = 'service_role')
  WITH CHECK (auth.role() = 'service_role');

CREATE POLICY "public_read_executions" ON growth_executions
  FOR SELECT
  USING (true);
